// Package mtproto — протокол туннеля «mtproto2» (v0.8, модуль
// protocol.mtproto2): MTProto 2.0-конверт payload'ов DATA/UDP_DATA.
//
// ГДЕ ИМЕННО ЖИВЁТ КРИПТО: приватный хендшейк ReverseRay (TLS 1.3 с
// SPKI-pin + HMAC токена) остаётся как есть — это наш «вход». Внутри него,
// после READY, при согласованном протоколе mtproto2 стороны договариваются
// о свежих ключах DH и дальше payload'ы DATA/UDP_DATA ходят в MTProto
// 2.0-конверте: [auth_key_id(8)][msg_key(16)][AES-256-IGE(тело)].
// Управляющие кадры (PING/WINDOW/CLOSE/OPEN/PROBE/STATS) не шифруются —
// это транспорт, а не содержимое.
//
// КРИПТОПАРАМЕТРЫ — канон MTProto 2.0 (совместимы с реализацией Telegram):
//   - DH: 2048-битная группа RFC 3526 group#2 (тот же простой модуль p,
//     что и у Telegram), g = 2, ключи по каноническим правилам
//     валидации (1 < g_a < p-1 и т.п.);
//   - auth_key = 256 байт big-endian g_ab;
//   - auth_key_id = SHA1(auth_key)[0:8] (маркер ключа, не крипто-примитив);
//   - msg_key = SHA256(auth_key[88+x:120+x] + plaintext)[8:24];
//   - AES key/IV из sha256_a/sha256_b по таблице MTProto 2.0;
//   - IGE-режим AES-256 (реализован поверх ECB — без внешних зависимостей).
//
// Отклонения от Telegram-сетки (сознательные, документированы):
//   - salt и session_id фиксируются на сессию при апгрейде (в Telegram их
//     шлёт сервер в service-message_new — нам нужен лишь уникальный ввод
//     KDF, туннель уже аутентифицирован);
//   - msg_id монотонный счётчик вместо time-based (туннель не переживает
//     сообщение о времени — только порядок/дедуп).
package mtproto

